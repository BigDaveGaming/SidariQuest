"""Import approved PNG masters already placed in art/raw. Requires Pillow."""
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "art/raw"
ASSETS = ROOT / "assets"
BACKGROUNDS = {
    "bg_van_hire", "bg_apartment_outside", "bg_apartment_kitchen", "bg_minimarket"
}
INTRO = {"intro_1_landing", "intro_2_baggage", "intro_3_arrivals"}
LOCALS = {
    "spyros_van": ("normal", "proud", "confused"),
    "eleni": ("normal", "pleased", "exasperated"),
    "kyrios_spyros": ("normal", "stern", "explaining"),
    "fat_spyros": ("normal", "laughing", "fed_up"),
}
EXPRESSIONS = ("normal", "proud", "confused", "cringe", "fuming", "shocked", "talking")
available = []


def convert(path, name, size=None, transparent=False, bounds=(1024, 1536)):
    if not path.is_file():
        return
    with Image.open(path) as master:
        image = master.convert("RGBA" if transparent else "RGB")
        if size and image.size != size:
            raise ValueError(f"{path}: expected {size}, got {image.size}")
        if transparent and image.getchannel("A").getextrema() != (0, 255):
            raise ValueError(f"{path}: needs both transparent and opaque pixels")
        image.thumbnail(bounds, Image.Resampling.LANCZOS)
        image.save(ASSETS / f"{name}.webp", quality=84, method=6)
        available.append(name)


for folder, names in (("backgrounds", BACKGROUNDS), ("intro", INTRO)):
    for name in sorted(names):
        convert(RAW / folder / f"{name}.png", name, (1024, 1536), bounds=(840, 1260))

# Keep the original undersized sheets and crops in their original folders.
approved = RAW / "approved"
for character, moods in LOCALS.items():
    for mood in moods:
        name = f"{character}_{mood}"
        convert(approved / "locals" / f"{name}.png", name, (1024, 1024), True, (640, 640))

for character in ("dave", "sharon"):
    for mood in EXPRESSIONS:
        name = f"{character}_{mood}"
        convert(approved / "characters" / f"{name}.png", name, (1024, 1024), True, (640, 640))
    name = f"{character}_full"
    convert(approved / "characters" / f"{name}.png", name, transparent=True, bounds=(520, 1000))

convert(RAW / "extras/fig.png", "fig", transparent=True, bounds=(96, 96))
icon = RAW / "extras/icon.png"
if icon.is_file():
    with Image.open(icon) as master:
        if master.size != (1024, 1024) or master.convert("RGBA").getchannel("A").getextrema() != (255, 255):
            raise ValueError("App icon must be opaque and 1024 × 1024")
        for size in (180, 192, 512):
            master.convert("RGB").resize((size, size), Image.Resampling.LANCZOS).save(ROOT / f"icon-{size}.png")

(ASSETS / "chapter1-art.js").write_text(
    "/* Generated by scripts/import-chapter1-art.py. */\n"
    f"const GAME_ART = {json.dumps(sorted(available))};\n"
)
